/**
 * Materialize .env files FROM the Total Recall secrets store.
 *
 * Model: TR secrets.enc is the SSOT for all user API keys.
 * Repo / deploy .env files are projections — never the other way around.
 *
 * Never write secret values into vault markdown, openwiki, or surfaces.
 */

import fs from 'node:fs';
import path from 'node:path';
import os from 'node:os';
import { loadSecrets, listSecretsMeta, resolveSecretsPath } from './secrets-store.mjs';

const META_KEY = '__tr_secrets_meta';

const BEGIN_MARK = '# BEGIN TOTAL-RECALL-SECRETS';
const END_MARK = '# END TOTAL-RECALL-SECRETS';

function envHeader() {
  return `${BEGIN_MARK}
# Generated by Total Recall — do not hand-edit secret values here.
# SSOT: secrets store (npx total-recall auth secret …)
# Re-export: npx total-recall auth secret export-env --path <repo>
# ${new Date().toISOString()}
`;
}

const ASSIGNMENT = /^\s*(?:export\s+)?([A-Za-z_][A-Za-z0-9_]*)\s*=/;

function assignedKey(line) {
  const m = ASSIGNMENT.exec(line);
  return m ? m[1] : null;
}

/** Drop assignments of `keys` from hand-managed text so the managed block is the only definition. */
function withoutKeys(text, keys) {
  if (!keys.size) return text;
  return text.split('\n').filter((line) => !keys.has(assignedKey(line))).join('\n');
}

/**
 * Merge a managed TR secrets block into an existing .env without wiping
 * non-secret / hand-managed keys outside the BEGIN/END markers.
 *
 * A key the block defines is removed from the text outside the block: dotenv
 * loaders disagree on whether the first or last assignment wins, so a stale
 * copy left outside would shadow the rotated value under some of them.
 * With `partial`, the block carries only some keys (a `--keys` deploy), so the
 * previous block's other entries are kept rather than dropped.
 *
 * @param {string} existing - current file contents (or '')
 * @param {string} managedBody - full block including BEGIN/END marks
 * @param {{ partial?: boolean }} [opts]
 * @returns {string}
 */
export function mergeEnvManagedBlock(existing, managedBody, { partial = false } = {}) {
  let managed = String(managedBody || '').trimEnd() + '\n';
  const text = existing == null ? '' : String(existing);

  if (!text.trim()) return managed;

  const beginIdx = text.indexOf(BEGIN_MARK);
  const endIdx = text.indexOf(END_MARK);
  const hasBlock = beginIdx !== -1 && endIdx !== -1 && endIdx > beginIdx;

  if (partial && hasBlock) {
    const fresh = new Set(managed.split('\n').map(assignedKey).filter(Boolean));
    const kept = text.slice(beginIdx, endIdx).split('\n')
      .filter((line) => { const key = assignedKey(line); return key && !fresh.has(key); });
    if (kept.length) {
      const end = managed.lastIndexOf(END_MARK);
      managed = `${managed.slice(0, end)}${kept.join('\n')}\n${managed.slice(end)}`;
    }
  }
  const managedKeys = new Set(managed.split('\n').map(assignedKey).filter(Boolean));

  if (hasBlock) {
    const before = withoutKeys(text.slice(0, beginIdx), managedKeys).replace(/\s+$/, '');
    const after = withoutKeys(text.slice(endIdx + END_MARK.length).replace(/^\r?\n?/, ''), managedKeys);
    const parts = [];
    if (before) parts.push(before.endsWith('\n') ? before : `${before}\n`);
    parts.push(managed.endsWith('\n') ? managed : `${managed}\n`);
    if (after.trim()) {
      parts.push(after.startsWith('\n') ? after : `\n${after}`);
    }
    return parts.join('').replace(/\n{3,}/g, '\n\n');
  }

  // No prior TR block — append managed section after existing content
  const rest = withoutKeys(text, managedKeys);
  const base = rest.endsWith('\n') ? rest : `${rest}\n`;
  return `${base}\n${managed}`;
}

/**
 * Refuse a shared plugin path as a secret-projection target.
 *
 * The shared plugin folder lives at `<agentDir>/skills/total-recall/plugins` and
 * normally holds one symlink per plugin pointing at that plugin's owner
 * checkout. A projection written there lands in a plugin repository, which is
 * not an application and must never hold an application's secrets.
 *
 * @param {string} abs absolute, existing directory
 */
export function assertNotSharedPluginPath(abs) {
  const agentDir = process.env.AGENT_DIR || process.env._TR_TEST_AGENT_DIR || path.join(os.homedir(), '.agent');
  const pluginsRoot = path.join(agentDir, 'skills', 'total-recall', 'plugins');
  const candidates = new Set([path.resolve(abs)]);
  try { candidates.add(fs.realpathSync(abs)); } catch { /* unreadable path */ }
  for (const candidate of candidates) {
    if (candidate === pluginsRoot || candidate.startsWith(pluginsRoot + path.sep)) {
      throw new Error(`Refusing to write secrets into the shared plugin folder: ${abs}. Name the application repository with --path.`);
    }
    let entries = [];
    try { entries = fs.readdirSync(pluginsRoot, { withFileTypes: true }); } catch { return; }
    for (const entry of entries) {
      if (!entry.isSymbolicLink()) continue;
      let target;
      try { target = fs.realpathSync(path.join(pluginsRoot, entry.name)); } catch { continue; }
      if (candidate === target || candidate.startsWith(target + path.sep)) {
        throw new Error(`Refusing to write secrets into the plugin checkout ${target} (reached as ${abs}). Name the application repository with --path.`);
      }
    }
  }
}

/**
 * Resolve a project slug from a filesystem path (last segment).
 * @param {string} projectPath
 */
export function projectSlugFromPath(projectPath) {
  if (!projectPath) return null;
  const abs = path.resolve(projectPath);
  // Bindings are stored trimmed, so a directory name with stray whitespace must match.
  return path.basename(abs).trim();
}

/**
 * Load project-registry entries (if any).
 */
export function loadProjectRegistry() {
  const registryPath = path.join(
    os.homedir(),
    '.agent',
    'skills',
    'total-recall',
    'config',
    'project-registry.json',
  );
  if (!fs.existsSync(registryPath)) return [];
  try {
    const data = JSON.parse(fs.readFileSync(registryPath, 'utf8'));
    return Array.isArray(data) ? data : [];
  } catch {
    return [];
  }
}

/**
 * Decide whether a secret meta row applies to a target project.
 *
 * @param {object} metaRow - from listSecretsMeta
 * @param {{ projectPath?: string, projectSlug?: string, includeGlobal?: boolean, keys?: string[] }} target
 */
export function secretMatchesTarget(metaRow, target = {}) {
  if (target.keys?.length && !target.keys.includes(metaRow.key)) return false;

  const slug = target.projectSlug || projectSlugFromPath(target.projectPath);
  const repos = Array.isArray(metaRow.repos) ? metaRow.repos : [];
  const projectPath = metaRow.project_path || '';

  // Explicit key list mode
  if (target.keys?.length) return true;

  // Bound to this repo by slug or path (a key may be bound to several repos)
  if (slug && repos.some((r) => r === slug || r === '*' || r.endsWith(`/${slug}`))) {
    return true;
  }
  if (target.projectPath && projectPath) {
    const a = path.resolve(target.projectPath);
    const b = path.resolve(projectPath);
    if (a === b || a.startsWith(b + path.sep) || b.startsWith(a + path.sep)) return true;
  }

  // Unbound secrets: include when includeGlobal (default true for full SSOT export)
  if (target.includeGlobal !== false && repos.length === 0 && !projectPath) {
    return true;
  }

  // Also include when tagged global scope with empty repos
  if (target.includeGlobal !== false && metaRow.scope === 'global' && repos.length === 0) {
    return true;
  }

  return false;
}

/**
 * Build dotenv body (KEY=value lines) for matching secrets.
 * @returns {{ body: string, keys: string[], exampleBody: string, count: number }}
 */
export async function buildEnvProjection(brainDir, target = {}) {
  const secrets = await loadSecrets(brainDir);
  const metaRows = await listSecretsMeta(brainDir);
  const byKey = new Map(metaRows.map((m) => [m.key, m]));

  const selected = [];
  for (const [key, value] of Object.entries(secrets)) {
    if (key === META_KEY) continue;
    if (value == null || value === '') continue;
    const meta = byKey.get(key) || { key, repos: [], scope: 'global' };
    if (!secretMatchesTarget(meta, target)) continue;
    const outKey = (target.rename && target.rename[key]) || key;
    selected.push({ key, outKey, value: String(value), meta });
  }

  selected.sort((a, b) => a.key.localeCompare(b.key));

  const lines = selected.map(({ outKey, value }) => {
    // Quote if needed
    const needsQuote = /[\s#"'$\\]/.test(value);
    const v = needsQuote ? JSON.stringify(value) : value;
    return `${outKey}=${v}`;
  });

  const exampleLines = selected.map(({ outKey }) => `${outKey}=`);

  const body = `${envHeader()}${lines.join('\n')}${lines.length ? '\n' : ''}${END_MARK}\n`;
  const exampleBody = `# Example env — names only. Values live in Total Recall secrets store.
# Generate real .env: npx total-recall auth secret export-env --path .
${exampleLines.join('\n')}${exampleLines.length ? '\n' : ''}`;

  return {
    body,
    exampleBody,
    keys: selected.map((s) => s.key),
    count: selected.length,
    store: resolveSecretsPath(brainDir),
    // [outKey, value] pairs for in-process comparison (remote verify). Never log them.
    entries: selected.map(({ outKey, value }) => [outKey, value]),
  };
}

/**
 * Write .env (and optional .env.example) into a project directory.
 *
 * @param {string} brainDir
 * @param {string} projectPath - repo root
 * @param {{
 *   filename?: string,
 *   example?: boolean,
 *   dryRun?: boolean,
 *   includeGlobal?: boolean,
 *   keys?: string[],
 *   mode?: number,
 * }} opts
 */
export async function exportEnvToProject(brainDir, projectPath, opts = {}) {
  const abs = path.resolve(projectPath);
  if (!fs.existsSync(abs) || !fs.statSync(abs).isDirectory()) {
    throw new Error(`Project path is not a directory: ${abs}`);
  }
  // A secret projection belongs to a repository. The shared plugin folder links
  // every plugin to its owner checkout, so exporting with the default cwd —
  // inside a plugin — wrote a plaintext .env of the whole store into 30 plugin
  // repositories. Refuse that target rather than requiring a flag to avoid it.
  assertNotSharedPluginPath(abs);

  const filename = opts.filename || '.env';
  const target = {
    projectPath: abs,
    projectSlug: projectSlugFromPath(abs),
    includeGlobal: opts.includeGlobal !== false,
    keys: opts.keys,
    rename: opts.rename,
  };

  const projection = await buildEnvProjection(brainDir, target);
  const envPath = path.join(abs, filename);
  const examplePath = path.join(abs, `${filename}.example`);

  if (opts.dryRun) {
    return {
      dryRun: true,
      envPath,
      examplePath: opts.example !== false ? examplePath : null,
      keys: projection.keys,
      count: projection.count,
      store: projection.store,
    };
  }

  const mode = opts.mode ?? 0o600;
  // Merge by default so non-secret APP_NAME=… etc. outside the TR block survive
  const replaceAll = opts.replaceAll === true;
  let finalBody = projection.body;
  let merged = false;
  if (!replaceAll && fs.existsSync(envPath)) {
    try {
      const existing = fs.readFileSync(envPath, 'utf8');
      finalBody = mergeEnvManagedBlock(existing, projection.body);
      merged = true;
    } catch {
      finalBody = projection.body;
    }
  }
  fs.writeFileSync(envPath, finalBody, { encoding: 'utf8', mode });
  try {
    fs.chmodSync(envPath, mode);
  } catch {
    /* windows / fs without chmod */
  }

  let wroteExample = false;
  if (opts.example !== false) {
    fs.writeFileSync(examplePath, projection.exampleBody, { encoding: 'utf8', mode: 0o644 });
    wroteExample = true;
  }

  // Ensure .env is gitignored
  ensureGitignoreHasEnv(abs);

  return {
    dryRun: false,
    envPath,
    examplePath: wroteExample ? examplePath : null,
    keys: projection.keys,
    count: projection.count,
    store: projection.store,
    projectSlug: target.projectSlug,
    merged,
  };
}

/**
 * Export to multiple registered projects.
 */
export async function exportEnvToRegistry(brainDir, opts = {}) {
  const registry = loadProjectRegistry();
  const results = [];
  for (const entry of registry) {
    const projectPath = entry.path || entry.project_root;
    if (!projectPath || !fs.existsSync(projectPath)) {
      results.push({
        name: entry.name,
        path: projectPath,
        ok: false,
        error: 'path missing',
      });
      continue;
    }
    try {
      const r = await exportEnvToProject(brainDir, projectPath, opts);
      results.push({ name: entry.name, ...r, ok: true });
    } catch (err) {
      results.push({ name: entry.name, path: projectPath, ok: false, error: err.message });
    }
  }
  return results;
}

/**
 * Build a deploy payload: dotenv text + optional JSON map (no disk write).
 */
export async function buildDeploySecretsPayload(brainDir, target = {}) {
  const projection = await buildEnvProjection(brainDir, {
    includeGlobal: true,
    ...target,
  });
  const secrets = await loadSecrets(brainDir);
  const map = {};
  for (const key of projection.keys) {
    if (secrets[key] != null) map[key] = String(secrets[key]);
  }
  return {
    dotenv: projection.body,
    map,
    keys: projection.keys,
    count: projection.count,
    store: projection.store,
  };
}

function ensureGitignoreHasEnv(projectPath) {
  const gi = path.join(projectPath, '.gitignore');
  const linesNeeded = ['.env', '.env.local', '.env.*.local'];
  let content = '';
  if (fs.existsSync(gi)) {
    content = fs.readFileSync(gi, 'utf8');
  }
  const missing = linesNeeded.filter((l) => !content.split(/\r?\n/).some((line) => line.trim() === l));
  if (!missing.length) return;
  const block = `\n# Total Recall secrets projections\n${missing.join('\n')}\n`;
  fs.appendFileSync(gi, content.endsWith('\n') || !content ? block : `\n${block}`);
}
