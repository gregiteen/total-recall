/**
 * Extension Routes
 *
 * GET /api/extension/download  — Download the Chrome extension as a zip/tar
 * GET /api/extension/status    — Check whether the extension is available and connected
 */

import { Router } from 'express';
import fs from 'node:fs';
import path from 'node:path';
import os from 'node:os';
import { spawn } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import { requireAuth, requireScope } from '../auth.mjs';
import { BRAIN_DIR, serverError } from './_shared.mjs';
import { issueKey } from '../keys.mjs';

const router = Router();

/**
 * GET /api/extension/download
 * Streams the Chrome extension directory as a .zip (or .tar.gz fallback)
 * with an automatically provisioned access token and brain URL baked into config.js/config.json.
 */
router.get('/api/extension/download', requireAuth, requireScope('config:read'), async (req, res) => {
  let tmpDir = null;
  try {
    // Extension lives at <package-root>/extension/
    const extDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../../../extension');
    if (!fs.existsSync(extDir) || !fs.existsSync(path.join(extDir, 'manifest.json'))) {
      return res.status(404).json({ error: 'Chrome extension not found in this installation.' });
    }

    // Determine the brain URL from request headers/host
    const proto = req.get('x-forwarded-proto') || req.protocol || 'http';
    const host = req.get('x-forwarded-host') || req.get('host') || '127.0.0.1:3000';
    const brainUrl = `${proto}://${host}`;

    // Automatically issue a dedicated access token for this extension package
    let token = '';
    try {
      const key = issueKey(`Chrome Extension (${host})`, { scopes: ['*'] });
      token = (key && key.token) || '';
    } catch {
      token = '';
    }

    // Create a temporary staging directory so git working copy remains untouched
    tmpDir = await fs.promises.mkdtemp(path.join(os.tmpdir(), 'tr-ext-'));
    await fs.promises.cp(extDir, tmpDir, { recursive: true });

    // Bake pre-configured credentials directly into config.js and config.json inside the package
    const configData = {
      brainUrl,
      pat: token,
      generatedAt: new Date().toISOString(),
      activeBrainId: req.headers['x-total-recall-brain'] || 'global',
    };

    const configJsContent = `// Automatically generated by Total Recall Brain\nself.TOTAL_RECALL_CONFIG = ${JSON.stringify(configData, null, 2)};\n`;
    await fs.promises.writeFile(path.join(tmpDir, 'config.js'), configJsContent, 'utf8');
    await fs.promises.writeFile(path.join(tmpDir, 'config.json'), JSON.stringify(configData, null, 2), 'utf8');

    res.setHeader('Content-Type', 'application/zip');
    res.setHeader('Content-Disposition', 'attachment; filename="total-recall-extension.zip"');

    const cleanup = () => {
      if (tmpDir) {
        fs.promises.rm(tmpDir, { recursive: true, force: true }).catch(() => {});
        tmpDir = null;
      }
    };

    res.on('finish', cleanup);
    res.on('close', cleanup);

    // Use zip if available, fall back to tar
    // Unit specs live beside the extension sources but are not part of the product.
    const zip = spawn('zip', ['-r', '-', '.', '-x', '*.spec.mjs'], { cwd: tmpDir, stdio: ['ignore', 'pipe', 'ignore'] });
    zip.stdout.pipe(res);
    zip.on('error', () => {
      // zip not available — try tar
      if (!res.headersSent) {
        res.setHeader('Content-Type', 'application/gzip');
        res.setHeader('Content-Disposition', 'attachment; filename="total-recall-extension.tar.gz"');
        const tar = spawn('tar', ['czf', '-', '--exclude=*.spec.mjs', '-C', tmpDir, '.'], { stdio: ['ignore', 'pipe', 'ignore'] });
        tar.stdout.pipe(res);
        tar.on('error', err => { cleanup(); if (!res.headersSent) serverError(res, err); });
        tar.on('close', () => { cleanup(); if (!res.writableEnded) res.end(); });
      }
    });
    zip.on('close', code => {
      cleanup();
      if (code !== 0 && !res.writableEnded) res.end();
    });
  } catch (err) {
    if (tmpDir) {
      fs.promises.rm(tmpDir, { recursive: true, force: true }).catch(() => {});
    }
    serverError(res, err);
  }
});

/**
 * GET /api/extension/status
 * Returns whether the extension is available (packaged) and connected (has sent captures).
 */
router.get('/api/extension/status', requireAuth, requireScope('config:read'), async (_req, res) => {
  try {
    const extDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../../../extension');
    const available = fs.existsSync(path.join(extDir, 'manifest.json'));
    let version = '0.0.0';
    if (available) {
      try {
        const manifest = JSON.parse(fs.readFileSync(path.join(extDir, 'manifest.json'), 'utf8'));
        version = manifest.version || '0.0.0';
      } catch {}
    }

    // Check if extension has ever connected by looking for the marker file
    const markerPath = path.join(BRAIN_DIR, 'config', '.extension-connected');
    const connected = fs.existsSync(markerPath);

    res.json({ available, connected, version });
  } catch (err) { serverError(res, err); }
});

export default router;
export { router as extensionRouter };
