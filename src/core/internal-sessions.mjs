import fs from 'node:fs';
import path from 'node:path';
import { atomicWrite } from './vault.mjs';

/** Prefix of every prompt Total Recall sends for its own background reasoning. */
export const INTERNAL_JOB_MARKER = '[total-recall:internal-job]';
// Exact role lines of reasoning prompts persisted before the marker existed.
const LEGACY_ROLES = [
  'You are a Session Post-Mortem Analyst for an AI memory system called Total Recall.',
  'You are a Rule Compliance Auditor for an AI memory system.',
];
// Metaharness bootstrap: the brief opens with the requester line and the task follows this line.
const BOOTSTRAP_OPENING = 'Requester:';
const BOOTSTRAP_WRAPPER = '\nRequested task:\n';
// Context Codex injects as user messages before the real prompt.
const INJECTED = /^(<environment_context>|<user_instructions>|<permissions|# AGENTS\.md instructions)/;

/** Metaharness children inherit this. Their hooks must not copy or queue anything. */
export function isInternalJobEnv(env = process.env) {
  return env.TR_META_HARNESS_RUN === '1';
}

function internalPrompt(text) {
  const body = text.trimStart();
  const wrapped = body.startsWith(BOOTSTRAP_OPENING) ? body.indexOf(BOOTSTRAP_WRAPPER) : -1;
  const candidates = [body, ...(wrapped < 0 ? [] : [body.slice(wrapped + BOOTSTRAP_WRAPPER.length).trimStart()])];
  return candidates.some(value => value.startsWith(INTERNAL_JOB_MARKER) || LEGACY_ROLES.some(role => value.startsWith(role)));
}

/**
 * True only when the session's root prompt is a Total Recall reasoning job. Later
 * turns and tool output that quote these prompts never make a user session internal.
 */
export function isInternalTranscript(entries) {
  if (!Array.isArray(entries)) return false;
  for (const entry of entries) {
    if (entry?.internal === true) return true;
    if (entry?.role !== 'user') continue;
    const text = typeof entry.content === 'string' ? entry.content : '';
    if (INJECTED.test(text.trimStart())) continue;
    return internalPrompt(text);
  }
  return false;
}

const controlFile = brainDir => path.join(brainDir, 'config', 'lessons.json');

export function readLessonControl(brainDir) {
  const file = controlFile(brainDir);
  if (!fs.existsSync(file)) return {};
  const value = JSON.parse(fs.readFileSync(file, 'utf8'));
  if (!value || typeof value !== 'object' || Array.isArray(value)) throw new Error(`Invalid lesson configuration: ${file}`);
  return value;
}

/** Paused, or disabled outright: either way nothing is queued, selected or run. */
export function isLessonsPaused(brainDir) {
  const config = readLessonControl(brainDir);
  return config.paused === true || config.enabled === false;
}

export function setLessonsPaused(brainDir, paused) {
  const config = readLessonControl(brainDir);
  if (paused) Object.assign(config, { paused: true, pausedAt: new Date().toISOString() });
  else { delete config.paused; delete config.pausedAt; }
  fs.mkdirSync(path.dirname(controlFile(brainDir)), { recursive: true });
  atomicWrite(controlFile(brainDir), JSON.stringify(config, null, 2) + '\n');
  return config;
}

/** Work generated by automatic lesson reviews: the reviews and the skill gaps they file. */
export function isAutomaticLessonTask(task) {
  const slug = String(task?.slug || '');
  if (slug.startsWith('lesson-review-') || task?.category === 'lesson-review' || task?.executor === 'lesson-review') return true;
  return slug.startsWith('skill-gap-') && (task?.created_by === 'post-mortem-engine' || task?.origin?.agent === 'post-mortem-engine');
}
